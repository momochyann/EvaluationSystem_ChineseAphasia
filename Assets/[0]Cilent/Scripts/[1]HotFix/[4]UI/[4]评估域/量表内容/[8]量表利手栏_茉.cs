using UnityEngine;
using System.Linq;

/// <summary>
/// 量表利手栏 - 使用栏目组统一管理
/// 包含1个维度：利手评定（选项组性）
/// 评定规则：
/// - 左利手：12项全部或前7项习惯用左手，后5项中任何1至5项习惯用另一只手
/// - 右利手：12项全部或前7项习惯用右手，后5项中任何1至5项习惯用另一只手
/// - 混合利手：前7项中1至6项习惯用一只手，其余用另一只手
/// </summary>
public class 量表利手栏_茉 : 量表评估基类_茉
{
    protected override string 获取记录字段名称() => "利手记录";

    protected override bool 检查是否全部完成()
    {
        if (栏目组性群 == null) return false;
        return 栏目组性群.TrueForAll(组 => 组?.是否全部已选择 ?? false);
    }

    protected override string 获取未完成提示信息() => "请完成全部利手评估后保存";

    protected override void 保存额外数据(object 记录)
    {
        var 利手记录 = 记录 as 利手记录;
        if (利手记录 == null || 栏目组性群 == null) return;

        // 计算利手评定结果
        foreach (var 栏目组 in 栏目组性群)
        {
            if (栏目组 == null) continue;
            
            if (栏目组.维度名称 == "利手评定")
            {
                利手记录.利手评定结果 = 计算利手类型(栏目组);
                Debug.Log($"[量表利手栏] 保存利手评定结果: {利手记录.利手评定结果}");
            }
        }
    }

    /// <summary>
    /// 根据选项组选择情况计算利手类型
    /// 选项索引：0=左手，1=右手
    /// </summary>
    private string 计算利手类型(栏目组性_茉 栏目组)
    {
        var 选项组列表 = 栏目组.获取选项组列表();
        if (选项组列表 == null || 选项组列表.Count < 12)
        {
            Debug.LogWarning("[量表利手栏] 选项组数量不足12个");
            return "未评定";
        }

        // 统计前7项的选择情况（索引0-6）
        int 前7项左手数 = 0;
        int 前7项右手数 = 0;
        for (int i = 0; i < 7; i++)
        {
            int 选中索引 = 选项组列表[i].当前选中索引;
            if (选中索引 == 0) 前7项左手数++;
            else if (选中索引 == 1) 前7项右手数++;
        }

        // 统计后5项的选择情况（索引7-11）
        int 后5项左手数 = 0;
        int 后5项右手数 = 0;
        for (int i = 7; i < 12; i++)
        {
            int 选中索引 = 选项组列表[i].当前选中索引;
            if (选中索引 == 0) 后5项左手数++;
            else if (选中索引 == 1) 后5项右手数++;
        }

        Debug.Log($"[量表利手栏] 前7项 - 左:{前7项左手数} 右:{前7项右手数}; 后5项 - 左:{后5项左手数} 右:{后5项右手数}");

        // 判断左利手：前7项全部用左手 且 后5项可以有1-5项用右手
        if (前7项左手数 == 7 && 后5项右手数 >= 0 && 后5项右手数 <= 5)
        {
            return "左利手";
        }

        // 判断右利手：前7项全部用右手 且 后5项可以有1-5项用左手
        if (前7项右手数 == 7 && 后5项左手数 >= 0 && 后5项左手数 <= 5)
        {
            return "右利手";
        }

        // 判断混合利手：前7项中1至6项习惯用一只手
        if (前7项左手数 >= 1 && 前7项左手数 <= 6)
        {
            return "混合利手";
        }
        if (前7项右手数 >= 1 && 前7项右手数 <= 6)
        {
            return "混合利手";
        }

        return "混合利手"; // 默认返回混合利手
    }
}
